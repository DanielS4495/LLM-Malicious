BATCH_SIZE = 5
ACTIVE_JUDGE_PROVIDER = "groq_llama-3.1"
MALWARE_JUDGE_PROVIDER = "groq_llama-3.1"

base_name = os.path.splitext(os.path.basename(INPUT_FILE))[0]
